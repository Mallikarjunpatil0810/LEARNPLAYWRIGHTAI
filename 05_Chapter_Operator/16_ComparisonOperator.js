// comparison operator in js
// ==, ===, !=, !==, >, <, >=, <=   
// = simple equality operator
let a = 10;
let b = "10";
// == operator checks for value equality
console.log(a == b); // Output: true    
console.log(a != b); // Output: false
console.log(a !== b); // Output: true checks for value and type equality
console.log(a === b); // Output: false


// === operator checks for value and type equality
console.log(a === b); // Output: false  

a = 10;
b = 20; 

console.log("Greater Than", a > b);
console.log("Less Than", a < b);
console.log("Greater Than or Equal To", a >= b);
console.log("Less Than or Equal To", a <= b);
